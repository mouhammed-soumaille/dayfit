"""Write every saved result into one LaTeX file (report/appendix_tables.tex).

The report text discusses the important numbers; this appendix lists ALL of them,
straight from the CSV files, so nothing we measured gets lost (including results
that a later experiment superseded). Re-run after any new experiment:

    python -m report.make_appendix
"""
import os

import pandas as pd

OUT = "report/appendix_tables.tex"


def tex(value):
    """Format one cell: round numbers, escape LaTeX special characters."""
    if isinstance(value, float):
        return f"{value:.3f}"
    text = str(value).replace("lookbench_real_streetlook_image", "LookBench")
    for a, b in [("\\", "/"), ("_", r"\_"), ("%", r"\%"), ("&", r"\&"), ("#", r"\#"),
                 ("->", r"$\to$")]:
        text = text.replace(a, b)
    return text


def table(df, caption):
    """A long table that may run over several pages."""
    cols = "l" * len(df.columns)
    lines = [r"{\scriptsize\setlength{\tabcolsep}{3pt}", r"\begin{longtable}{" + cols + "}",
             r"\caption{" + caption + r"}\\", r"\toprule",
             " & ".join(tex(c) for c in df.columns) + r" \\", r"\midrule", r"\endhead"]
    for row in df.itertuples(index=False):
        lines.append(" & ".join(tex(v) for v in row) + r" \\")
    lines += [r"\bottomrule", r"\end{longtable}}", ""]
    return "\n".join(lines)


def with_ci(df, metric):
    """Merge a metric and its CI columns into one 'value [lo, hi]' column."""
    return [f"{m:.3f} [{lo:.3f}, {hi:.3f}]" for m, lo, hi in
            zip(df[metric], df[metric + "_lo"], df[metric + "_hi"])]


def main():
    parts = [r"\section{All results}\label{app:all}",
             "Every result saved in \\texttt{results/} and \\texttt{models/}, generated by "
             "\\texttt{report/make\\_appendix.py}. Includes results that later experiments superseded.", ""]

    if os.path.exists("results/summary.csv"):
        d = pd.read_csv("results/summary.csv")
        t = pd.DataFrame({"method": d["method"], "condition": d["condition"], "n": d["n_queries"],
                          "Recall@1": with_ci(d, "Recall@1"), "Recall@5": with_ci(d, "Recall@5"),
                          "P@5": with_ci(d, "Precision@5"), "ms": d["mean_latency_ms"].round(1)})
        parts.append(table(t, "Synthetic test set: every method and condition, 95\\% bootstrap CIs."))

    if os.path.exists("results/lowres/summary.csv"):
        d = pd.read_csv("results/lowres/summary.csv")
        keep = [c for c in ["method", "condition", "n_queries", "Recall@1", "Recall@5", "Precision@5"] if c in d]
        parts.append(table(d[keep], "Low-resolution (60x80) catalogue, before switching to high resolution."))

    if os.path.exists("results/lookbench_summary.csv"):
        d = pd.read_csv("results/lookbench_summary.csv")
        t = pd.DataFrame({"method": d["method"], "query": d["query_image"], "n": d["n_queries"],
                          "Recall@1": with_ci(d, "Recall@1"), "Recall@5": with_ci(d, "Recall@5"),
                          "category P@5": with_ci(d, "CategoryP@5")})
        parts.append(table(t, "LookBench real\\_streetlook, every method run."))

    if os.path.exists("results/comparisons.csv"):
        d = pd.read_csv("results/comparisons.csv")
        d = d.rename(columns={"p_value": "p", "significant": "sig."})
        d["metric"] = d["metric"].replace({"Precision@5": "P@5"})
        parts.append(table(d, "Every paired bootstrap test (difference = after $-$ before; "
                              "p = 0.0 means $p<0.0005$ with 2,000 resamples)."))

    for path, name in [("models/finetune_log.csv", "same-type hard batches"),
                       ("models/finetune_random_log.csv", "random batches (ablation)")]:
        if os.path.exists(path):
            parts.append(table(pd.read_csv(path), f"Fine-tuning log, {name}."))

    if os.path.exists("results/type_similarity.csv"):
        parts.append(table(pd.read_csv("results/type_similarity.csv"),
                           "Type structure of the catalogue embeddings (T2)."))

    if os.path.exists("results/conformal.csv"):
        d = pd.read_csv("results/conformal.csv")
        parts.append(table(d.drop(columns=["target"]).rename(columns={"coverage": "cov", "mean_size": "mean size", "median_size": "median size",
                        "singleton_rate": "single rate", "singleton_accuracy": "single acc"}), "Conformal sets on synthetic photos, every alpha."))

    if os.path.exists("results/conformal_shift.csv"):
        d = pd.read_csv("results/conformal_shift.csv")
        parts.append(table(d.drop(columns=["target"]), "Conformal sets on LookBench: synthetic vs real calibration (T1)."))

    if os.path.exists("results/conformal_tv.csv"):
        parts.append(table(pd.read_csv("results/conformal_tv.csv"),
                           "Histogram TV between synthetic and real scores, and the bound 0.9 $-$ TV (T1)."))

    if os.path.exists("results/conformal_mondrian.csv"):
        parts.append(table(pd.read_csv("results/conformal_mondrian.csv").rename(columns={
            "n_queries": "n", "coverage_standard": "cov std", "median_size_standard": "size std",
            "coverage_mondrian": "cov Mondrian", "median_size_mondrian": "size Mondrian"}),
                           "Per-category coverage and median set size, standard vs Mondrian (T3), alpha = 0.1."))

    if os.path.exists("results/conformal_risk.csv"):
        parts.append(table(pd.read_csv("results/conformal_risk.csv"),
                           "Conformal risk control on wrong-category share (T4)."))

    with open(OUT, "w") as f:
        f.write("\n".join(parts))
    print(f"saved {OUT}")


if __name__ == "__main__":
    main()
